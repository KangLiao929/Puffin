def overlap_depth_scale(ref_depth, cur_depth, min_valid=100):
    """Median depth ratio of the SAME frame under two chunks' scale gauges.

    ref_depth: the overlap view's depth kept from the previous chunk.
    cur_depth: the same view's depth regenerated by the current chunk.
    Returns the multiplicative factor that maps the current chunk onto the
    previous chunk's scale (1.0 when too few pixels are jointly valid).
    """
    ref = ref_depth.float()
    cur = cur_depth.float()
    valid = (torch.isfinite(ref) & torch.isfinite(cur)
             & (ref > 0) & (cur > 0))
    if valid.any():
        # visionbanana saturates sky/invalid to huge finite depths; those
        # pixels ratio to ~1 in both gauges and drag the median away from
        # the real scene scale — mirror the glb unprojection's 20x-median
        # cutoff before taking the median.
        ref_med = torch.median(ref[valid])
        cur_med = torch.median(cur[valid])
        valid &= (ref <= 20.0 * ref_med) & (cur <= 20.0 * cur_med)
    if int(valid.sum()) < min_valid:
        return 1.0
    return float(torch.median(ref[valid] / cur[valid]))


def overlap_depth_affine(ref_depth, cur_depth, min_valid=100):
    """Robust AFFINE gauge fit on the SAME overlap frame: ref ~ s*cur + t.

    Trimmed least squares: fit, drop residual outliers (> 2.5*MAD), refit
    (3 rounds). Saturated visionbanana sky is excluded as in
    overlap_depth_scale. Falls back to (median ratio, 0.0) when the fit is
    degenerate (near-constant depth / negative slope) and to (1.0, 0.0)
    when too few pixels are jointly valid.
    """
    ref = ref_depth.float().flatten()
    cur = cur_depth.float().flatten()
    valid = (torch.isfinite(ref) & torch.isfinite(cur)
             & (ref > 0) & (cur > 0))
    if valid.any():
        ref_med = torch.median(ref[valid])
        cur_med = torch.median(cur[valid])
        valid &= (ref <= 20.0 * ref_med) & (cur <= 20.0 * cur_med)
    if int(valid.sum()) < min_valid:
        return 1.0, 0.0
    x, y = cur[valid], ref[valid]
    s, t = 1.0, 0.0
    for _ in range(3):
        mx, my = x.mean(), y.mean()
        vx = float(((x - mx) ** 2).mean())
        if vx < 1e-12:   # constant depth: the slope is unobservable
            return float(torch.median(y / x)), 0.0
        s = float((((x - mx) * (y - my)).mean()) / vx)
        t = float(my - s * mx)
        r = (y - (s * x + t)).abs()
        keep = r <= 2.5 * torch.median(r) + 1e-8
        if int(keep.sum()) < min_valid:
            break
        x, y = x[keep], y[keep]
    if s <= 0:   # nonsensical fit; fall back to the median ratio
        return float(torch.median(y / x)), 0.0
    return s, t


def reencode_depth_vis(depth_hw):
    """Re-encode a (rescaled) scalar depth map as a visionbanana RGB tensor
    [3, H, W] in [-1, 1], so PNG/GIF panels match the aligned depths."""
    valid = torch.isfinite(depth_hw) & (depth_hw > 0)
    vb = depth_to_visionbanana(depth_hw, valid)   # [H, W, 3] in [-1, 1]
    return vb.permute(2, 0, 1).contiguous()


