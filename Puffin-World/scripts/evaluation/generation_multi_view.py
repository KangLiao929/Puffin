def parse_combo_specs(args):
    """Parse inline --combo_traj specs ('2r+' '4p-' ...) into the per-chunk
    motion list [(token, deg_per_view), ...] of length --chunk.

    Chunk indices are 1-based; every chunk not named in a spec follows the
    dataset's GT trajectory (token 't', deg None). Degrees come from
    --combo_deg (one per spec, default 4 deg/view each)."""
    if not args.combo_traj:
        return None
    if args.chunk <= 1:
        raise ValueError("--combo_traj requires chunked mode (--chunk > 1).")

    degs = args.combo_deg if args.combo_deg is not None \
        else [4.0] * len(args.combo_traj)
    if len(degs) != len(args.combo_traj):
        raise ValueError(
            f"--combo_deg needs exactly one value per --combo_traj spec "
            f"({len(args.combo_traj)} specs), got {len(degs)}.")

    motions = [('t', None)] * args.chunk
    seen = set()
    for spec, deg in zip(args.combo_traj, degs):
        idx_s, token = spec[:-2], spec[-2:]
        if (not idx_s.isdigit() or len(token) != 2
                or token[0] not in ('r', 'p', 'y') or token[1] not in ('+', '-')):
            raise ValueError(
                f"Bad --combo_traj spec {spec!r} "
                f"(expected '<chunk><r|p|y><+|->', e.g. '2r+').")
        idx = int(idx_s)
        if not 1 <= idx <= args.chunk:
            raise ValueError(
                f"--combo_traj spec {spec!r}: chunk index must be in "
                f"[1, {args.chunk}] (1-based).")
        if idx in seen:
            raise ValueError(f"--combo_traj: chunk {idx} specified twice.")
        seen.add(idx)
        motions[idx - 1] = (token, float(deg))

    print("[combo_traj] per-chunk motions: " + ", ".join(
        tok if deg is None else f"{tok}({deg:g} deg/view)"
        for tok, deg in motions))
    return motions


