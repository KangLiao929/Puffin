def _depth_np(d):
    """Depth tensor/array -> float32 numpy with invalid pixels zeroed."""
    arr = (d.detach().cpu().float().numpy() if isinstance(d, torch.Tensor)
           else np.asarray(d, dtype=np.float32))
    return np.where(np.isfinite(arr) & (arr > 0), arr, 0.0)


